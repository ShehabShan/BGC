# Parse raw
lines = raw.splitlines()
entries = []
i=0
while i < len(lines):
    line=lines[i].strip()
    if not line:
        i+=1
        continue
    m=re.match(r'^(\d{13})\s*(.*)', line)
    if m:
        sid=m.group(1)
        name=m.group(2).strip()
        # Check next line if it doesn't start with 13 digits, it's continuation of name
        # Peek next line
        if i+1 < len(lines):
            nxt=lines[i+1].strip()
